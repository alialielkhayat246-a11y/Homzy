drop policy if exists appt_blackouts_own on public.appt_blackouts;
create policy appt_blackouts_own on public.appt_blackouts for select to authenticated using (broker_id = auth.uid());
drop policy if exists appointments_parties on public.appointments;
create policy appointments_parties on public.appointments for select to authenticated
  using (broker_id = auth.uid() or client_id = auth.uid());
drop policy if exists appointment_events_parties on public.appointment_events;
create policy appointment_events_parties on public.appointment_events for select to authenticated
  using (exists (select 1 from public.appointments a where a.id = appointment_id
                 and (a.broker_id = auth.uid() or a.client_id = auth.uid())));
drop policy if exists appointment_reminders_own on public.appointment_reminders;
create policy appointment_reminders_own on public.appointment_reminders for select to authenticated using (user_id = auth.uid());

-- ---------------------------------------------------------------- helpers
create or replace function public._appt_cfg(p_broker uuid)
returns public.appt_settings language sql stable security definer set search_path = public as $$
  select coalesce(
    (select s from public.appt_settings s where s.broker_id = p_broker),
    row(p_broker, 2, 60, 24, 2, 30, now())::public.appt_settings);
$$;

create or replace function public._appt_notify(p_user uuid, p_type text, p_title text, p_body text, p_data jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare nid bigint;
begin
  insert into public.crm_notifications(user_id, type, title, body, data, push_state)
  values (p_user, p_type, p_title, p_body, coalesce(p_data, '{}'::jsonb), 'queued')
  returning id into nid;
  return nid;
end $$;

create or replace function public._appt_when(p_at timestamptz)
returns text language sql stable as $$
  select to_char(p_at at time zone 'Africa/Cairo', 'YYYY-MM-DD') || ' — ' ||
         to_char(p_at at time zone 'Africa/Cairo', 'HH12:MI') ||
         case when extract(hour from p_at at time zone 'Africa/Cairo') < 12 then ' ص' else ' م' end;
$$;

-- Why a slot can't be booked (null = bookable). p_skip = the appointment being
-- rescheduled, so it doesn't conflict with itself.
create or replace function public._appt_slot_problem(p_listing uuid, p_broker uuid, p_start timestamptz,
                                                     p_end timestamptz, p_skip uuid default null)
returns text language plpgsql stable security definer set search_path = public as $$
declare
  c   public.appt_settings := public._appt_cfg(p_broker);
  d   date := (p_start at time zone 'Africa/Cairo')::date;
  t1  time := (p_start at time zone 'Africa/Cairo')::time;
  t2  time := (p_end   at time zone 'Africa/Cairo')::time;
  dow int  := extract(dow from (p_start at time zone 'Africa/Cairo'))::int;
  n   int;
begin
  if p_end <= p_start or (p_end at time zone 'Africa/Cairo')::date <> d then return 'invalid_time'; end if;
  if p_start < now() + make_interval(hours => c.min_notice_hours) then return 'too_soon'; end if;
  if p_start > now() + make_interval(days => c.horizon_days) then return 'too_far'; end if;
  -- broker hours (default 10:00–20:00 every day when none are set)
  if exists (select 1 from public.appt_availability where broker_id = p_broker and listing_id is null) then
    if not exists (select 1 from public.appt_availability where broker_id = p_broker and listing_id is null
                   and weekday = dow and start_time <= t1 and end_time >= t2) then
      return 'broker_unavailable'; end if;
  elsif t1 < time '10:00' or t2 > time '20:00' then
    return 'broker_unavailable';
  end if;
  -- owner hours for this property (no rows = no extra restriction)
  if p_listing is not null and exists (select 1 from public.appt_availability where listing_id = p_listing) then
    if not exists (select 1 from public.appt_availability where listing_id = p_listing
                   and weekday = dow and start_time <= t1 and end_time >= t2) then
      return 'owner_unavailable'; end if;
  end if;
  -- blackouts: broker-wide or this property, whole day or a time range
  if exists (select 1 from public.appt_blackouts b
             where b.broker_id = p_broker and b.day = d
               and (b.listing_id is null or b.listing_id = p_listing)
               and (b.start_time is null or (b.start_time < t2 and b.end_time > t1))) then
    return case when exists (select 1 from public.appt_blackouts b where b.broker_id = p_broker and b.day = d
                             and b.listing_id = p_listing and (b.start_time is null or (b.start_time < t2 and b.end_time > t1)))
                then 'owner_unavailable' else 'broker_unavailable' end;
  end if;
  -- the broker's shared schedule: no overlap with any active appointment
  if exists (select 1 from public.appointments a
             where a.broker_id = p_broker and a.status in ('pending', 'confirmed')
               and (a.status <> 'pending' or a.hold_expires_at > now())
               and (p_skip is null or a.id <> p_skip)
               and tstzrange(a.starts_at, a.ends_at, '[)') && tstzrange(p_start, p_end, '[)')) then
    return 'slot_taken'; end if;
  -- daily limit (pending requests count)
  select count(*) into n from public.appointments a
   where a.broker_id = p_broker and a.local_day = d and a.status in ('pending', 'confirmed')
     and (a.status <> 'pending' or a.hold_expires_at > now())
     and (p_skip is null or a.id <> p_skip);
  if n >= c.daily_limit then return 'daily_limit'; end if;
  return null;
end $$;

-- release pending requests whose hold ran out
create or replace function public._appt_expire()
returns int language plpgsql security definer set search_path = public as $$
declare r record; n int := 0;
begin
  for r in select * from public.appointments
            where status = 'pending' and hold_expires_at <= now() for update skip locked loop
    update public.appointments set status = 'cancelled', cancelled_by = 'system', status_reason = 'expired',
           closed_at = now(), updated_at = now() where id = r.id;
    insert into public.appointment_events(appointment_id, actor_role, action, from_status, to_status)
    values (r.id, 'system', 'expired', 'pending', 'cancelled');
    perform public._appt_notify(r.client_id, 'appt_expired', 'طلب المعاينة انتهى',
      'البروكر مارَدّش على طلب معاينة "' || coalesce(r.listing_title, '') || '" يوم ' || public._appt_when(r.starts_at)
      || ' في الوقت المحدد، فالميعاد اتلغى. تقدر تحجز ميعاد تاني.',
      jsonb_build_object('appointment_id', r.id, 'url', '/my-bookings'));
    perform public._appt_notify(r.broker_id, 'appt_expired', 'طلب معاينة انتهى من غير رد',
      coalesce(r.client_name, '') || ' — ' || coalesce(r.listing_title, '') || ' — ' || public._appt_when(r.starts_at),
      jsonb_build_object('appointment_id', r.id, 'url', '/appointments?id=' || r.id));
    n := n + 1;
  end loop;
  return n;
end $$;

-- (re)plan the 24h / 2h / 30m reminders of a confirmed appointment
create or replace function public._appt_plan_reminders(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare a public.appointments%rowtype; k record; who record;
begin
  select * into a from public.appointments where id = p_id;
  if not found then return; end if;
  if a.status <> 'confirmed' then
    update public.appointment_reminders set status = 'cancelled'
     where appointment_id = p_id and status = 'scheduled';
    return;
  end if;
  for who in select a.broker_id as uid, 'broker'::text as aud union all select a.client_id, 'client' loop
    for k in select * from (values ('24h', interval '24 hours'), ('2h', interval '2 hours'), ('30m', interval '30 minutes')) v(kind, lead) loop
      insert into public.appointment_reminders(appointment_id, user_id, audience, kind, due_at, status, sent_at, notification_id)
      values (p_id, who.uid, who.aud, k.kind, a.starts_at - k.lead,
              case when a.starts_at - k.lead > now() then 'scheduled' else 'skipped' end, null, null)
      on conflict (appointment_id, user_id, kind) do update
        set due_at = excluded.due_at, status = excluded.status, sent_at = null, notification_id = null;
    end loop;
  end loop;
end $$;

-- keep the CRM viewings log (My Day, performance) in step with a confirmed appointment
create or replace function public._appt_sync_viewing(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare a public.appointments%rowtype; l public.listings%rowtype; vid bigint; st text;
begin
  select * into a from public.appointments where id = p_id;
  if not found then return; end if;
  st := case a.status when 'confirmed' then 'confirmed' when 'completed' then 'done' else 'cancelled' end;
  if a.viewing_id is null then
    if a.status <> 'confirmed' then return; end if;
    select * into l from public.listings where id = a.listing_id;
    insert into public.crm_viewings(lead_id, owner_id, property_kind, property_ref, property_title, scheduled_at, location, status, notes)
    values (a.lead_id, a.broker_id, 'listing', a.listing_id::text, a.listing_title, a.starts_at,
            nullif(concat_ws(' — ', l.area, l.address), ''), st, a.client_notes)
    returning id into vid;
    update public.appointments set viewing_id = vid where id = p_id;
  else
    update public.crm_viewings set scheduled_at = a.starts_at, status = st where id = a.viewing_id;
  end if;
end $$;

-- ------------------------------------------------------------ public RPCs
-- Bookable slots of a listing on a Cairo day (anyone may look; booking needs login).
create or replace function public.appt_available_slots(p_listing uuid, p_day date)
returns table(starts_at timestamptz, ends_at timestamptz, label text)
language plpgsql volatile security definer set search_path = public as $$
declare l public.listings%rowtype; c public.appt_settings; w record; t timestamptz; dow int;
begin
  perform public._appt_expire();
  select * into l from public.listings where id = p_listing and status = 'active';
  if not found then return; end if;
  c := public._appt_cfg(l.owner_id);
  dow := extract(dow from p_day)::int;
  for w in
    select a.start_time, a.end_time from public.appt_availability a
     where a.broker_id = l.owner_id and a.listing_id is null and a.weekday = dow
    union all
    select time '10:00', time '20:00'
     where not exists (select 1 from public.appt_availability a where a.broker_id = l.owner_id and a.listing_id is null)
    order by 1
  loop
    t := (p_day + w.start_time) at time zone 'Africa/Cairo';
    while t + make_interval(mins => c.slot_minutes) <= (p_day + w.end_time) at time zone 'Africa/Cairo' loop
      if public._appt_slot_problem(p_listing, l.owner_id, t, t + make_interval(mins => c.slot_minutes)) is null then
        starts_at := t; ends_at := t + make_interval(mins => c.slot_minutes);
        label := to_char(t at time zone 'Africa/Cairo', 'HH24:MI');
        return next;
      end if;
      t := t + make_interval(mins => c.slot_minutes);
    end loop;
  end loop;
end $$;

-- Which of the next days still have a free slot (to grey out the day picker).
create or replace function public.appt_open_days(p_listing uuid, p_days int default 14)
returns table(day date, slots int)
language plpgsql volatile security definer set search_path = public as $$
declare d date := (now() at time zone 'Africa/Cairo')::date;
begin
  for i in 0 .. greatest(1, least(p_days, 60)) - 1 loop
    day := d + i;
    select count(*) into slots from public.appt_available_slots(p_listing, d + i);
    return next;
  end loop;
end $$;

create or replace function public.appt_book(p_listing uuid, p_starts_at timestamptz, p_name text,
                                            p_phone text, p_notes text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  uid uuid := auth.uid(); l public.listings%rowtype; c public.appt_settings; e timestamptz; d date;
  err text; aid uuid; hold timestamptz; lead uuid; v_phone text; agency uuid;
begin
  if uid is null then return jsonb_build_object('ok', false, 'error', 'login_required'); end if;
  select * into l from public.listings where id = p_listing and status = 'active';
  if not found then return jsonb_build_object('ok', false, 'error', 'listing_unavailable'); end if;
  if l.owner_id = uid then return jsonb_build_object('ok', false, 'error', 'own_listing'); end if;
  if coalesce(length(trim(p_name)), 0) < 2 then return jsonb_build_object('ok', false, 'error', 'name_required'); end if;
  v_phone := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
  if length(v_phone) < 10 or length(v_phone) > 15 then return jsonb_build_object('ok', false, 'error', 'phone_invalid'); end if;
  -- one open request per listing, and at most 3 open requests per client
  if exists (select 1 from public.appointments where client_id = uid and listing_id = p_listing
             and status in ('pending', 'confirmed') and starts_at > now()) then
    return jsonb_build_object('ok', false, 'error', 'already_booked'); end if;
  if (select count(*) from public.appointments where client_id = uid and status = 'pending' and hold_expires_at > now()) >= 3 then
    return jsonb_build_object('ok', false, 'error', 'too_many_pending'); end if;

  c := public._appt_cfg(l.owner_id);
  e := p_starts_at + make_interval(mins => c.slot_minutes);
  d := (p_starts_at at time zone 'Africa/Cairo')::date;
  perform public._appt_expire();
  -- serialise bookings of this broker for this day (daily limit is atomic)
  perform pg_advisory_xact_lock(hashtextextended(l.owner_id::text || d::text, 0));
  err := public._appt_slot_problem(p_listing, l.owner_id, p_starts_at, e);
  if err is not null then return jsonb_build_object('ok', false, 'error', err); end if;

  -- the client becomes (or already is) a lead in the broker's CRM
  select id into lead from public.clients
   where owner_id = l.owner_id and right(regexp_replace(coalesce(clients.phone, ''), '\D', '', 'g'), 10) = right(v_phone, 10)
     and deleted_at is null limit 1;
  if lead is null then
    select agency_id into agency from public.agency_members where user_id = l.owner_id and status = 'active' limit 1;
    insert into public.clients(owner_id, agency_id, name, phone, whatsapp, purpose, type, area, stage, source, notes, created_by)
    values (l.owner_id, agency, trim(p_name), p_phone, p_phone, l.purpose, l.type, l.area, 'viewing', 'viewing_booking',
            'طلب معاينة: ' || coalesce(l.title, ''), uid)
    returning id into lead;
  end if;

  hold := least(now() + make_interval(hours => c.pending_hold_hours), p_starts_at);
  begin
    insert into public.appointments(listing_id, listing_title, broker_id, client_id, lead_id, client_name, client_phone,
                                    client_notes, starts_at, ends_at, local_day, status, hold_expires_at)
    values (p_listing, l.title, l.owner_id, uid, lead, trim(p_name), p_phone, nullif(trim(coalesce(p_notes, '')), ''),
            p_starts_at, e, d, 'pending', hold)
    returning id into aid;
  exception when exclusion_violation then
    return jsonb_build_object('ok', false, 'error', 'slot_taken');
  end;
  insert into public.appointment_events(appointment_id, actor_id, actor_role, action, to_status, to_start)
  values (aid, uid, 'client', 'requested', 'pending', p_starts_at);
  perform public._appt_notify(l.owner_id, 'appt_request', 'طلب معاينة جديد',
    trim(p_name) || ' عايز يعاين "' || coalesce(l.title, '') || '" يوم ' || public._appt_when(p_starts_at)
    || ' — أكّد أو ارفض قبل ' || public._appt_when(hold),
    jsonb_build_object('appointment_id', aid, 'url', '/appointments?id=' || aid));
  return jsonb_build_object('ok', true, 'id', aid, 'status', 'pending', 'hold_expires_at', hold, 'starts_at', p_starts_at);
end $$;

-- confirm / reject / complete (broker) — cancel (broker or client)
create or replace function public.appt_action(p_id uuid, p_action text, p_reason text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); a public.appointments%rowtype; role text; ns text;
begin
  select * into a from public.appointments where id = p_id for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'not_found'); end if;
  role := case when a.broker_id = uid then 'broker' when a.client_id = uid then 'client' end;
  if role is null then return jsonb_build_object('ok', false, 'error', 'forbidden'); end if;
  if p_action in ('confirm', 'reject', 'complete') and role <> 'broker' then
    return jsonb_build_object('ok', false, 'error', 'forbidden'); end if;

  if p_action = 'confirm' then
    if a.status <> 'pending' then return jsonb_build_object('ok', false, 'error', 'bad_status'); end if;
    if a.hold_expires_at <= now() or a.starts_at <= now() then
      perform public._appt_expire(); return jsonb_build_object('ok', false, 'error', 'expired'); end if;
    ns := 'confirmed';
  elsif p_action = 'reject' then
    if a.status <> 'pending' then return jsonb_build_object('ok', false, 'error', 'bad_status'); end if;
    ns := 'rejected';
  elsif p_action = 'complete' then
    if a.status <> 'confirmed' then return jsonb_build_object('ok', false, 'error', 'bad_status'); end if;
    if a.starts_at > now() + interval '1 hour' then return jsonb_build_object('ok', false, 'error', 'not_started'); end if;
    ns := 'completed';
  elsif p_action = 'cancel' then
    if a.status not in ('pending', 'confirmed') then return jsonb_build_object('ok', false, 'error', 'bad_status'); end if;
    ns := 'cancelled';
  else
    return jsonb_build_object('ok', false, 'error', 'bad_action');
  end if;

  update public.appointments set
    status = ns, updated_at = now(),
    confirmed_at = case when ns = 'confirmed' then now() else confirmed_at end,
    closed_at = case when ns in ('rejected', 'cancelled', 'completed') then now() else closed_at end,
    hold_expires_at = case when ns = 'confirmed' then null else hold_expires_at end,
    status_reason = case when ns in ('rejected', 'cancelled') then nullif(trim(coalesce(p_reason, '')), '') else status_reason end,
    cancelled_by = case when ns = 'cancelled' then role else cancelled_by end
  where id = p_id;
  insert into public.appointment_events(appointment_id, actor_id, actor_role, action, from_status, to_status, note)
  values (p_id, uid, role, ns, a.status, ns, p_reason);
  perform public._appt_plan_reminders(p_id);
  perform public._appt_sync_viewing(p_id);

  if ns = 'confirmed' then
    perform public._appt_notify(a.client_id, 'appt_confirmed', 'تم تأكيد ميعاد المعاينة ✅',
      'معاينة "' || coalesce(a.listing_title, '') || '" يوم ' || public._appt_when(a.starts_at),
      jsonb_build_object('appointment_id', p_id, 'url', '/my-bookings'));
    perform public._appt_notify(a.broker_id, 'appt_confirmed', 'أكّدت معاينة',
      a.client_name || ' — ' || coalesce(a.listing_title, '') || ' — ' || public._appt_when(a.starts_at),
      jsonb_build_object('appointment_id', p_id, 'url', '/appointments?id=' || p_id));
  elsif ns = 'rejected' then
    perform public._appt_notify(a.client_id, 'appt_rejected', 'طلب المعاينة اترفض',
      'معاينة "' || coalesce(a.listing_title, '') || '" يوم ' || public._appt_when(a.starts_at)
      || coalesce(' — ' || nullif(trim(coalesce(p_reason, '')), ''), '') || '. تقدر تختار ميعاد تاني.',
      jsonb_build_object('appointment_id', p_id, 'url', '/my-bookings'));
  elsif ns = 'cancelled' then
    perform public._appt_notify(case when role = 'broker' then a.client_id else a.broker_id end, 'appt_cancelled',
      'ميعاد معاينة اتلغى',
      coalesce(a.listing_title, '') || ' — ' || public._appt_when(a.starts_at)
      || case when role = 'client' then ' — ألغاه ' || a.client_name else ' — ألغاه البروكر' end
      || coalesce(' — ' || nullif(trim(coalesce(p_reason, '')), ''), ''),
      jsonb_build_object('appointment_id', p_id, 'url', case when role = 'broker' then '/my-bookings' else '/appointments?id=' || p_id end));
  end if;
  return jsonb_build_object('ok', true, 'status', ns);
end $$;

-- move an appointment. Broker: stays confirmed (reminders re-planned). Client:
-- a confirmed appointment goes back to pending for the broker to accept.
create or replace function public.appt_reschedule(p_id uuid, p_new_start timestamptz, p_reason text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); a public.appointments%rowtype; role text; c public.appt_settings;
        e timestamptz; d date; err text; ns text; hold timestamptz;
begin
  select * into a from public.appointments where id = p_id for update;
  if not found then return jsonb_build_object('ok', false, 'error', 'not_found'); end if;
  role := case when a.broker_id = uid then 'broker' when a.client_id = uid then 'client' end;
  if role is null then return jsonb_build_object('ok', false, 'error', 'forbidden'); end if;
  if a.status not in ('pending', 'confirmed') then return jsonb_build_object('ok', false, 'error', 'bad_status'); end if;
  c := public._appt_cfg(a.broker_id);
  e := p_new_start + make_interval(mins => c.slot_minutes);
  d := (p_new_start at time zone 'Africa/Cairo')::date;
  perform public._appt_expire();
  perform pg_advisory_xact_lock(hashtextextended(a.broker_id::text || d::text, 0));
  err := public._appt_slot_problem(a.listing_id, a.broker_id, p_new_start, e, p_id);
  if err is not null then return jsonb_build_object('ok', false, 'error', err); end if;
  ns := case when role = 'client' then 'pending' else a.status end;
  hold := case when ns = 'pending' then least(now() + make_interval(hours => c.pending_hold_hours), p_new_start) end;
  begin
    update public.appointments set starts_at = p_new_start, ends_at = e, local_day = d, status = ns,
           hold_expires_at = hold, updated_at = now(),
           confirmed_at = case when ns = 'pending' then null else confirmed_at end
     where id = p_id;
  exception when exclusion_violation then
    return jsonb_build_object('ok', false, 'error', 'slot_taken');
  end;
  insert into public.appointment_events(appointment_id, actor_id, actor_role, action, from_status, to_status, from_start, to_start, note)
  values (p_id, uid, role, 'rescheduled', a.status, ns, a.starts_at, p_new_start, p_reason);
  perform public._appt_plan_reminders(p_id);
  perform public._appt_sync_viewing(p_id);
  perform public._appt_notify(case when role = 'broker' then a.client_id else a.broker_id end, 'appt_rescheduled',
    'ميعاد معاينة اتغيّر',
    coalesce(a.listing_title, '') || ': من ' || public._appt_when(a.starts_at) || ' إلى ' || public._appt_when(p_new_start)
    || case when ns = 'pending' and role = 'client' then ' — محتاج تأكيدك' else '' end,
    jsonb_build_object('appointment_id', p_id,
                       'url', case when role = 'broker' then '/my-bookings' else '/appointments?id=' || p_id end));
  return jsonb_build_object('ok', true, 'status', ns, 'starts_at', p_new_start);
end $$;

-- the broker's appointments with listing and client details
