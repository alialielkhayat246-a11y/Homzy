-- Property viewing appointments (booking system integrated with the CRM).
--
-- Rules enforced here, not in the browser:
--   * one broker schedule shared by all their listings: no two active
--     (pending/confirmed) appointments of a broker may overlap in time
--     (GiST exclusion constraint — safe under concurrent requests);
--   * a configurable daily limit per broker (default 2), counted under an
--     advisory lock on (broker, Cairo day) so two simultaneous bookings can't
--     both pass; pending requests count, rejected/cancelled don't;
--   * both the broker's working hours and the owner's (per-listing) viewing
--     hours must contain the slot; blackout days/time ranges are excluded;
--   * a pending request holds the slot until the broker answers or the hold
--     expires (configurable), after which the slot is released;
--   * reminders 24h / 2h / 30m before, for broker and client, generated by a
--     pg_cron tick into crm_notifications (and pushed by the backend).
-- All times are timestamptz; days and working hours are read in Africa/Cairo.

create extension if not exists pg_cron;
create extension if not exists pg_net;

-- ---------------------------------------------------------------- settings
create table if not exists public.appt_settings (
  broker_id          uuid primary key references auth.users(id) on delete cascade,
  daily_limit        int  not null default 2  check (daily_limit between 1 and 20),
  slot_minutes       int  not null default 60 check (slot_minutes in (30, 45, 60, 90, 120)),
  pending_hold_hours int  not null default 24 check (pending_hold_hours between 1 and 168),
  min_notice_hours   int  not null default 2  check (min_notice_hours between 0 and 72),
  horizon_days       int  not null default 30 check (horizon_days between 1 and 120),
  updated_at         timestamptz not null default now()
);

-- weekly windows: listing_id null = the broker's own hours (shared by every
-- listing); listing_id set = the owner's viewing hours for that property.
create table if not exists public.appt_availability (
  id         bigserial primary key,
  broker_id  uuid not null references auth.users(id) on delete cascade,
  listing_id uuid references public.listings(id) on delete cascade,
  weekday    smallint not null check (weekday between 0 and 6),   -- 0 = Sunday (extract(dow))
  start_time time not null,
  end_time   time not null,
  check (end_time > start_time)
);
create index if not exists appt_availability_idx on public.appt_availability(broker_id, listing_id, weekday);

-- unavailable dates / excluded time ranges (null times = the whole day)
create table if not exists public.appt_blackouts (
  id         bigserial primary key,
  broker_id  uuid not null references auth.users(id) on delete cascade,
  listing_id uuid references public.listings(id) on delete cascade,
  day        date not null,
  start_time time,
  end_time   time,
  note       text,
  check ((start_time is null and end_time is null) or (start_time is not null and end_time > start_time))
);
create index if not exists appt_blackouts_idx on public.appt_blackouts(broker_id, day);

-- ------------------------------------------------------------ appointments
create table if not exists public.appointments (
  id              uuid primary key default gen_random_uuid(),
  listing_id      uuid references public.listings(id) on delete set null,
  listing_title   text,                         -- snapshot, survives listing deletion
  broker_id       uuid not null references auth.users(id) on delete cascade,
  client_id       uuid not null references auth.users(id) on delete cascade,
  lead_id         uuid references public.clients(id) on delete set null,
  viewing_id      bigint,                       -- mirror row in crm_viewings once confirmed
  client_name     text not null,
  client_phone    text not null,
  client_notes    text,
  broker_notes    text,
  starts_at       timestamptz not null,
  ends_at         timestamptz not null,
  local_day       date not null,                -- Cairo calendar day (daily limit)
  status          text not null default 'pending'
                  check (status in ('pending', 'confirmed', 'rejected', 'cancelled', 'completed')),
  hold_expires_at timestamptz,
  status_reason   text,
  cancelled_by    text check (cancelled_by in ('client', 'broker', 'system')),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  confirmed_at    timestamptz,
  closed_at       timestamptz,
  check (ends_at > starts_at),
  constraint appointments_no_overlap exclude using gist (
    broker_id with =, tstzrange(starts_at, ends_at, '[)') with &&
  ) where (status in ('pending', 'confirmed'))
);
create index if not exists appointments_broker_time_idx on public.appointments(broker_id, starts_at);
create index if not exists appointments_client_idx on public.appointments(client_id, starts_at desc);
create index if not exists appointments_listing_idx on public.appointments(listing_id);
create index if not exists appointments_pending_idx on public.appointments(hold_expires_at) where status = 'pending';
create index if not exists appointments_day_idx on public.appointments(broker_id, local_day) where status in ('pending', 'confirmed');

create table if not exists public.appointment_events (
  id             bigserial primary key,
  appointment_id uuid not null references public.appointments(id) on delete cascade,
  actor_id       uuid,
  actor_role     text,                          -- client | broker | system
  action         text not null,                 -- requested | confirmed | rejected | cancelled | completed | rescheduled | expired
  from_status    text,
  to_status      text,
  from_start     timestamptz,
  to_start       timestamptz,
  note           text,
  created_at     timestamptz not null default now()
);
create index if not exists appointment_events_idx on public.appointment_events(appointment_id, created_at);

create table if not exists public.appointment_reminders (
  id              bigserial primary key,
  appointment_id  uuid not null references public.appointments(id) on delete cascade,
  user_id         uuid not null,
  audience        text not null check (audience in ('broker', 'client')),
  kind            text not null check (kind in ('24h', '2h', '30m')),
  due_at          timestamptz not null,
  status          text not null default 'scheduled' check (status in ('scheduled', 'sent', 'cancelled', 'skipped')),
  sent_at         timestamptz,
  notification_id bigint,
  unique (appointment_id, user_id, kind)
);
create index if not exists appointment_reminders_due_idx on public.appointment_reminders(due_at) where status = 'scheduled';

-- push delivery tracking on the existing notification centre
alter table public.crm_notifications
  add column if not exists push_state text,     -- queued | sent | no_device | failed
  add column if not exists pushed_at  timestamptz;
create index if not exists crm_notifications_push_idx on public.crm_notifications(created_at) where push_state = 'queued';

