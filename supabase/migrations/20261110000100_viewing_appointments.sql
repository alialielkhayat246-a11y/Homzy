-- ------------------------------------------------------------------ tick
-- every minute (pg_cron): release expired holds, emit due reminders
create or replace function public._appt_tick()
returns jsonb language plpgsql security definer set search_path = public as $$
declare r record; a public.appointments%rowtype; l public.listings%rowtype; nid bigint; sent int := 0; expired int;
        lead_txt text;
begin
  expired := public._appt_expire();
  for r in select * from public.appointment_reminders
            where status = 'scheduled' and due_at <= now() order by due_at for update skip locked loop
    select * into a from public.appointments where id = r.appointment_id;
    if a.status <> 'confirmed' or a.starts_at <= now() then
      update public.appointment_reminders set status = 'skipped' where id = r.id; continue;
    end if;
    select * into l from public.listings where id = a.listing_id;
    lead_txt := case r.kind when '24h' then 'بكرة' when '2h' then 'كمان ساعتين' else 'كمان نص ساعة' end;
    if r.audience = 'broker' then
      nid := public._appt_notify(r.user_id, 'appt_reminder', '⏰ معاينة ' || lead_txt,
        coalesce(a.listing_title, '') || ' — ' || public._appt_when(a.starts_at) || ' — العميل: ' || a.client_name
        || ' ' || a.client_phone,
        jsonb_build_object('appointment_id', a.id, 'kind', r.kind, 'url', '/appointments?id=' || a.id));
    else
      nid := public._appt_notify(r.user_id, 'appt_reminder', '⏰ ميعاد معاينتك ' || lead_txt,
        coalesce(a.listing_title, '') || ' — ' || public._appt_when(a.starts_at)
        || coalesce(' — ' || nullif(concat_ws('، ', l.area, l.address), ''), ''),
        jsonb_build_object('appointment_id', a.id, 'kind', r.kind, 'url', '/my-bookings'));
    end if;
    update public.appointment_reminders set status = 'sent', sent_at = now(), notification_id = nid where id = r.id;
    sent := sent + 1;
  end loop;
  return jsonb_build_object('expired', expired, 'reminders', sent);
end $$;

-- push delivery (backend): queued notifications with the user's devices
create or replace function public.notif_push_queue(p_key text, p_limit int default 50)
returns jsonb language plpgsql security definer set search_path = public as $$
declare out jsonb;
begin
  if not public._check_cron_key(p_key) then raise exception 'forbidden' using errcode = '42501'; end if;
  -- nobody to push to -> settled straight away
  update public.crm_notifications n set push_state = 'no_device', pushed_at = now()
   where n.push_state = 'queued' and not exists (select 1 from public.push_subscriptions s where s.user_id = n.user_id);
  update public.crm_notifications set push_state = 'failed', pushed_at = now()
   where push_state = 'queued' and created_at < now() - interval '1 day';
  select coalesce(jsonb_agg(jsonb_build_object('id', n.id, 'title', n.title, 'body', n.body,
                                               'url', coalesce(n.data->>'url', '/'),
                                               'subs', (select jsonb_agg(s.subscription) from public.push_subscriptions s where s.user_id = n.user_id))), '[]'::jsonb)
    into out
    from (select * from public.crm_notifications where push_state = 'queued' order by created_at limit least(p_limit, 200)) n;
  return out;
end $$;

create or replace function public.notif_push_mark(p_key text, p_ids bigint[], p_state text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public._check_cron_key(p_key) then raise exception 'forbidden' using errcode = '42501'; end if;
  update public.crm_notifications set push_state = p_state, pushed_at = now() where id = any(p_ids);
end $$;

